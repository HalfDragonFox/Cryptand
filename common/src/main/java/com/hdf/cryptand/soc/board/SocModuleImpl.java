package com.hdf.cryptand.soc.board;

/**
 * ===== 具体模块（集成底层抽象，2026-09-18）=====
 *
 * <p>用户定案："接口 + 速率 以及寄存器映射以及内存映射等方式，底层是这个，然后具体模块集成此底层
 * 抽象为具体模块，总之是数据传输，当然具体模块需要实现一些代码比如 PCIE 的转接这种，I2C 不同设备
 * 的分发这种，需要实现模拟的代码，然后对于 RV 来说要么就是内存直接写要么就是调用寄存器，
 * 一般不用操作 GPIO 口的，这样也不现实，通过抽象的方式实现"。</p>
 *
 * <h3>分层（这一层就是"具体模块"的家）</h3>
 * <pre>
 *   底层抽象（虚拟机提供）  ：接口 + 速率 + 寄存器映射 + 内存映射
 *   具体模块（本接口的实现）：PCIe 转接 / I2C 地址分发 / 显存窗口 / 控制器…
 *   RV（固件）             ：只会做两件事 —— 写内存窗口、写寄存器
 * </pre>
 *
 * <p>🔴 <b>RV 不操作 GPIO</b>：不做"引脚级软件时序"那条路（用户定案："这样也不现实"）。
 * 引脚/协议时序是<b>模块实现的内部事</b>：固件只管往窗口写字节，模块自己决定怎么把它变成
 * 一次 PCIe 转接、一次 I2C 分发、一次 8080 时序。</p>
 *
 * <p>已实现的两个例子：{@link I2cDispatchModule}（一条总线挂多从设备，按地址分发）、
 * {@link PcieBridgeModule}（上游窗口写 → 转接给指定下游目标）。</p>
 */
public interface SocModuleImpl {

    /** 模块的声明（接口 + 速率 + 寄存器/内存窗口）—— 由 {@link SocModules} 校验 */
    SocModule spec();

    /**
     * 把模块挂到板上：注册寄存器窗口、内存窗口、中断源与步进器。
     *
     * <p>这里就是"底层抽象被具体模块集成"的那一刻：模块把自己暴露成 RV 能看到的东西
     * （一段 MMIO 窗口），而它内部怎么实现协议（转接/分发）对 RV 完全不可见。</p>
     */
    void attach(SocBoard.Builder board);

    /** 每 tick 推进（传输、分发、回压恢复）—— 平台在 tick 边界按真实经过时间调用 */
    default void tick(long elapsedNanos) {
    }

    /** 模块的**内存映射窗口**基址（显存/FIFO/共享缓冲；0 = 本模块只有寄存器窗口） */
    default long memoryBase() {
        return 0;
    }

    /** 内存映射窗口大小（0 = 无内存窗口） */
    default int memorySpan() {
        return 0;
    }
}
