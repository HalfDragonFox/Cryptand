/**
 * ===== 内嵌 8×8 位图字体（common，纯 Java 零 MC，2026-09-27）=====
 *
 * <p><b>为什么要内嵌一份字模</b>：真彩屏对 OC 呈现为<b>普通 screen</b>（字符 + 16 色），
 * TEXT 模式的画面必须把设备的字符格（字符 + 每格前景/背景）画成像素 —— 而 MC 侧只有方块贴图，
 * 没有「8×8 字符字形」这种东西。字形是<b>纯数据</b>，按项目纪律（{@code AGENTS.md}：
 * 能写成纯 Java 的一律放 common）放在这里：两个 loader 与离线闸门读的是同一份字节，
 * 而且它<b>拿掉 Minecraft 一样成立</b>。</p>
 *
 * <h3>字模来源（CP437 ROM 字模）</h3>
 * <p><b>IBM PC / VGA BIOS 的 8×8 CP437 ROM 字模</b>：{@code 256 字形 × 8 行，每行 1 字节}
 * = 2048 字节。这就是 DOS/BIOS 文本模式下那张经典字模表（{@code 0x00} ☺☻♥、
 * {@code 0xB0-0xDF} 制表符与实心块、{@code 0xE0-0xFF} 希腊字母与数学符号全在其中）。
 * 字节出处：{@code https://github.com/spacerace/romfont} 的 {@code font-bin/IBM_VGA_8x8.bin}
 * （提取自 IBM VGA ROM 的 {@code VGA-ROM.F08}，随 qemu/seabios 以 public domain 分发；
 * 位图字形的设计本身不受版权保护，它是被最广泛再分发的位图字体）。</p>
 *
 * <p>⚠ <b>只有这一份字模</b>：任何「再抄一张表」的做法（例如另抄一份 Unicode 码点表）都是第二份真相。
 * Unicode → 字形号的映射<b>不抄表</b>，用 JDK 自带的码页现算 —— 而且是
 * {@link DisplayCharset#CP437} 那一张（固件单字节字符走的是同一个码页 ⇒ 两边天然一致，不会各错各的）。</p>
 *
 * <h3>位序（照 VGA 文本模式）</h3>
 * <p>每行 1 字节，<b>bit7 = 最左像素</b>（bit0 = 最右），8 行自上而下。
 * 于是 {@code pixel(code, x, y)} = 第 {@code y} 行的第 {@code (7 - x)} 位。</p>
 *
 * <p>跑法（离线闸门）：{@code ./gradlew :common:runFontTest}</p>
 */
