    /** Unicode → 字形号：升序码位表（二分查找的前提） */
    private static final char[] UNICODE;

    /** 与 {@link #UNICODE} 一一对应的字形号（并行数组） */
    private static final byte[] CODES;

    /** 字形号 → Unicode 字符（{@link #unicodeOf} 用；没有对应码位的为 0） */
    private static final char[] CHAR_BY_CODE = new char[GLYPH_COUNT];

    static {
        final Charset cp437 = DisplayCharset.CP437;
        final char[] uni = new char[GLYPH_COUNT];
        final byte[] codes = new byte[GLYPH_COUNT];
        final byte[] one = new byte[1];
        int n = 0;
        for (int b = 0; b < GLYPH_COUNT; b++) {
            one[0] = (byte) b;
            final String s = new String(one, cp437);
            if (s.length() != 1) {
                continue;                       // 一个字节解不出一个字符 ⇒ 这个字节没有可查的码位
            }
            uni[n] = s.charAt(0);
            codes[n] = (byte) b;
            CHAR_BY_CODE[b] = s.charAt(0);
            n++;
        }
        // 按码位升序（二分查找的前提）：只有 256 项，插入排序足够，也没有装箱/比较器开销
        for (int i = 1; i < n; i++) {
            final char key = uni[i];
            final byte val = codes[i];
            int j = i - 1;
            while (j >= 0 && uni[j] > key) {
                uni[j + 1] = uni[j];
                codes[j + 1] = codes[j];
                j--;
            }
            uni[j + 1] = key;
            codes[j + 1] = val;
        }
        UNICODE = Arrays.copyOf(uni, n);
        CODES = Arrays.copyOf(codes, n);
    }

    private TextFont8x8() {
    }

    /** 字模字节数（闸门断言「256 字形 × 8 字节」用） */
    public static int romBytes() {
        return ROM.length;
    }

    /** 码页里有多少个字模能与 Unicode 一一对应（正常 = 256） */
    public static int mappedCodes() {
        return UNICODE.length;
    }

    /**
     * 第 {@code code} 个字形的第 {@code y} 行原始字节（{@code 0..255}）。
     *
     * <p>越界<b>明确报错</b>（不静默返回空白 —— 那样只会画出一片黑，查不出问题在哪）。</p>
     */
    public static int row(int code, int y) {
        requireCode(code);
        requireRow(y);
        return ROM[code * GLYPH_H + y] & 0xFF;
    }

    /**
     * 字形位：{@code code} 字形的 {@code (x, y)} 是否点亮。
     *
     * @param x 0（最左）..7（最右）
     * @param y 0（最上）..7（最下）
     */
    public static boolean pixel(int code, int x, int y) {
        requireCode(code);
        requireRow(y);
        if (x < 0 || x >= GLYPH_W) {
            throw new IllegalArgumentException("字形 x 越界：0.." + (GLYPH_W - 1) + "，给了 " + x);
        }
        return ((ROM[code * GLYPH_H + y] >> (GLYPH_W - 1 - x)) & 1) != 0;
    }

    /** 整格空白（8 行全 0）—— 空格、NUL 以及码页里「我们不用」的那一段都是（闸门钉住） */
    public static boolean blank(int code) {
        requireCode(code);
        for (int y = 0; y < GLYPH_H; y++) {
            if (ROM[code * GLYPH_H + y] != 0) {
                return false;
            }
        }
        return true;
    }

    /**
     * Unicode 字符 → 字形号。
     *
     * <p>字体里<b>没有</b>这个字符 ⇒ 返回 {@code -1}。本类**绝不**静默换一个近似字形或者
     * 悄悄画成空格：调用方（渲染器）自己决定怎么办，并且可以据此报一次原因。</p>
     */
    public static int glyphOf(char ch) {
        final int at = Arrays.binarySearch(UNICODE, ch);
        return at < 0 ? -1 : (CODES[at] & 0xFF);
    }

    public static boolean hasGlyph(char ch) {
        return glyphOf(ch) >= 0;
    }

    /** 字形号 → Unicode 字符（诊断与闸门用；该字形没有对应码位时返回 0） */
    public static char unicodeOf(int code) {
        requireCode(code);
        return CHAR_BY_CODE[code];
    }

    private static void requireCode(int code) {
        if (code < 0 || code >= GLYPH_COUNT) {
            throw new IllegalArgumentException("字形号越界：0.." + (GLYPH_COUNT - 1) + "，给了 " + code);
        }
    }

    private static void requireRow(int y) {
        if (y < 0 || y >= GLYPH_H) {
            throw new IllegalArgumentException("字形行越界：0.." + (GLYPH_H - 1) + "，给了 " + y);
        }
    }
