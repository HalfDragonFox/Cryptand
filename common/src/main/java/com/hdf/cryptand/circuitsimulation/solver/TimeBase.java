package com.hdf.cryptand.circuitsimulation.solver;

/**
 * 时间基准接口（2026-08-30 用户：物理核心定义时间基准获取接口，允许
 * 【真实时间】或【仿真时间】推进两种方式）。
 * <p>
 * 统一的时间推进入口——状态演化（电机转速 / 温度 / 电容充电 / 能量）经
 * {@link #advance()} 获取本次推进的 dt，不依赖具体时钟实现：
 * <ul>
 *   <li>{@link SimClock}：真实时间模式——dt = 距上次 advance 的真实流逝
 *       （主线程心跳门控：主线程卡死 → 不推进，时间只由主线程驱动）；</li>
 *   <li>{@link SimulatedTimeBase}：仿真时间模式——固定步长，确定性可复现
 *       （EDA / 测试 / 回放场景）。</li>
 * </ul>
 * 与求解轮次解耦：无论求解频率（上限 100Hz，实际轮次由计算速度决定）如何，
 * 每轮推进"该轮真实覆盖的时间" → 状态演化绑定时间基准（1 倍速），不因
 * 轮次多少而超速/减速。
 * <p>
 * <b>每实例可用（2026-08-30 用户：以便多个客户端使用）</b>：本接口为实例级
 * ——每个客户端 / 会话 / 仿真场景持有【各自独立的 TimeBase 实例】（真实时间
 * 的 SimClock 或固定步长的 SimulatedTimeBase），互不干扰（时间/预算/心跳
 * 按实例独立）。物理核心经注入的 TimeBase 获取时间，不依赖全局单例。
 */
public interface TimeBase {

    /** 当前累计仿真时间（s；只读） */
    double time();

    /** 最近一次推进的 dt（s；0 = 未推进/暂停） */
    double lastDt();

    /**
     * 推进并返回本次 dt（s）：
     * <ul>
     *   <li>真实时间模式：距上次调用本方法的真实流逝（clamp [0.01, 1.0]；
     *       主线程心跳超时 → 0）；</li>
     *   <li>仿真时间模式：固定步长（外部驱动运行标志）。</li>
     * </ul>
     */
    double advance();

    /** 时间基准是否运行（真实模式=主线程心跳存活；仿真模式=外部驱动标志） */
    boolean isAlive();

    /**
     * 消耗 1 次推进预算（真实模式 SimClock 覆写：预算令牌 + 主线程心跳看门狗；
     * 仿真模式默认 true——固定步长无预算）。每实例独立。
     */
    default boolean consumeStep() { return true; }

    /** 重置（世界重载/新仿真场景） */
    void reset();
}
